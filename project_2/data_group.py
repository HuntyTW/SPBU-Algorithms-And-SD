# Создание итоговой структуры
def build_medical_data(doctors_data):
    doctors = {
        profile: []
        for profile in DOCTOR_PROFILES
    }

    # Добавляем категорию для исследований
    research_types = {
        "Лабораторные исследования": set(),
        "Функциональные исследования": set(),
        "Инструментальные исследования": set(),
        "Эндоскопические исследования": set(),
        "Осмотры и тестирования": set(),
        "Другие исследования": set(),
    }

    # Связываем специальности с группами
    profile_by_specialty = {
        specialty: profile
        for profile, specialties in DOCTOR_PROFILES.items()
        for specialty in specialties
    }

    for doctor in doctors_data:
        specialty = doctor["specialty"]

        # Определяем группу врача
        profile = profile_by_specialty.get(
            specialty, "Другие специалисты"
        )

        doctors[profile].append(doctor)

        # Группируем исследования
        for research in doctor.get("analyses", []):
            category = classify_research(research)
            research_types[category].add(research)

    # Преобразуем множества в отсортированные списки
    research_types = {
        category: sorted(items)
        for category, items in research_types.items()
    }

    return {
        "Врачи": doctors,
        "Исследования": research_types,
    }


# Формируем справочник
